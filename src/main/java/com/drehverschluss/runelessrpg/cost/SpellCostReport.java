package com.drehverschluss.runelessrpg.cost;

import com.drehverschluss.runelessrpg.RunelessRPG;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import net.minecraft.core.Holder;
import net.minecraft.core.Registry;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.neoforged.fml.loading.FMLPaths;
import net.spell_engine.api.spell.Spell;
import net.spell_engine.api.spell.registry.SpellRegistry;
import net.spell_engine.internals.casting.SpellCast;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;

/** Writes {@code config/runelessrpg/spell_costs_report.json}: every spell with category, tier and base cost. */
public final class SpellCostReport {
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private SpellCostReport() {}

    public record Result(int spells, Path file) {}

    public static Result write(MinecraftServer server) {
        Path file = FMLPaths.CONFIGDIR.get().resolve(RunelessRPG.MODID).resolve("spell_costs_report.json");
        try {
            Registry<Spell> registry = SpellRegistry.from(server.overworld());
            List<Holder.Reference<Spell>> spells = registry.holders()
                    .sorted(Comparator.comparing(holder -> holder.key().location().toString()))
                    .toList();
            JsonArray array = new JsonArray();
            for (Holder.Reference<Spell> holder : spells) {
                Spell spell = holder.value();
                SpellCostInfo info = ManaCosts.resolve(server.overworld(), holder);
                ResourceKey<Spell> key = holder.key();
                JsonObject entry = new JsonObject();
                entry.addProperty("id", key.location().toString());
                entry.addProperty("mod", key.location().getNamespace());
                entry.addProperty("type", String.valueOf(spell.type));
                entry.addProperty("category", info.category().name());
                entry.addProperty("source", info.source().name());
                entry.addProperty("tier", spell.tier);
                entry.addProperty("cast", spell.active != null ? SpellCast.Mode.from(spell).name() : "PASSIVE");
                int ticks = spell.active != null ? spell.active.cast.channelTicks() : 0;
                entry.addProperty("channelTicks", ticks);
                entry.addProperty("baseCost", info.baseCost());
                if (info.channeled() && ticks > 0) {
                    entry.addProperty("baseCostPerTick", info.baseCost() / ticks);
                }
                array.add(entry);
            }
            JsonObject root = new JsonObject();
            root.addProperty("note", "Base costs without player attributes (mana_cost, overcharge). Generated by RunelessRPG.");
            root.add("spells", array);
            Files.createDirectories(file.getParent());
            Files.writeString(file, GSON.toJson(root), StandardCharsets.UTF_8);
            return new Result(spells.size(), file);
        } catch (Exception ex) {
            RunelessRPG.LOGGER.error("Failed to write spell cost report {}", file, ex);
            return new Result(-1, file);
        }
    }
}
